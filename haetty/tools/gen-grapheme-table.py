#!/usr/bin/env python3
"""Writes haetty-vt's grapheme break table (crates/haetty-vt/src/grapheme_table.rs).

usage: tools/gen-grapheme-table.py UCD_DIR [OUT]

UCD_DIR is the Unicode Character Database libghostty-vt builds with: the ucd/
folder of the uucode package in Zig's cache (libghostty-vt 0.2.2 uses
uucode-0.2.0, Unicode 17.0), e.g.
~/.cache/zig/p/uucode-0.2.0-ZZjBPqZVVABQepOqZHR7vV_NcaN-wats0IB6o-Exj6m9/ucd.
The classes are derived as uucode derives its `grapheme_break` (build/
tables.zig): emoji modifier, emoji modifier base and extended pictographic
first, then Indic_Conjunct_Break, then the plain property (DESIGN.md §10.7).
"""
import pathlib
import re
import sys

CLASSES = [
    "Other", "Control", "Prepend", "CR", "LF", "RegionalIndicator", "SpacingMark",
    "L", "V", "T", "LV", "LVT", "Zwj", "Zwnj", "ExtendedPictographic",
    "EmojiModifierBase", "EmojiModifier", "InCBExtend", "InCBLinker", "InCBConsonant",
]
ORIGINAL = {
    "Prepend": "Prepend", "CR": "CR", "LF": "LF", "Control": "Control",
    "Extend": "Extend", "Regional_Indicator": "RegionalIndicator",
    "SpacingMark": "SpacingMark", "L": "L", "V": "V", "T": "T", "LV": "LV",
    "LVT": "LVT", "ZWJ": "Zwj",
}


def ranges(path, prop_re):
    """(start, end, value) for every line of a UCD property file."""
    out = []
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        m = prop_re.match(line)
        if not m:
            continue
        a, b, v = m.group(1), m.group(2) or m.group(1), m.group(3)
        out.append((int(a, 16), int(b, 16), v))
    return out


def main():
    ucd = pathlib.Path(sys.argv[1])
    out_path = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "crates/haetty-vt/src/grapheme_table.rs")
    one = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)\s*$")
    incb = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*InCB\s*;\s*([A-Za-z]+)\s*$")
    gcb = {}
    for a, b, v in ranges(ucd / "auxiliary/GraphemeBreakProperty.txt", one):
        for cp in range(a, b + 1):
            gcb[cp] = ORIGINAL[v]
    emoji = {"Emoji_Modifier": set(), "Emoji_Modifier_Base": set(), "Extended_Pictographic": set()}
    for a, b, v in ranges(ucd / "emoji/emoji-data.txt", one):
        if v in emoji:
            emoji[v].update(range(a, b + 1))
    icb = {}
    for a, b, v in ranges(ucd / "DerivedCoreProperties.txt", incb):
        for cp in range(a, b + 1):
            icb[cp] = v
    cls = {}
    for cp in set(gcb) | set().union(*emoji.values()) | set(icb):
        if cp in emoji["Emoji_Modifier"]:
            c = "EmojiModifier"
        elif cp in emoji["Emoji_Modifier_Base"]:
            c = "EmojiModifierBase"
        elif cp in emoji["Extended_Pictographic"]:
            c = "ExtendedPictographic"
        else:
            i = icb.get(cp, "None")
            o = gcb.get(cp, "Other")
            if i == "None":
                if o == "Extend":
                    assert cp == 0x200C, hex(cp)
                    c = "Zwnj"
                else:
                    c = o
            elif i == "Extend":
                c = "Zwj" if cp == 0x200D else "InCBExtend"
            elif i == "Linker":
                c = "InCBLinker"
            else:
                c = "InCBConsonant"
        if c != "Other":
            cls[cp] = c
    rows = []
    for cp in sorted(cls):
        c = CLASSES.index(cls[cp])
        if rows and rows[-1][1] + 1 == cp and rows[-1][2] == c:
            rows[-1][1] = cp
        else:
            rows.append([cp, cp, c])
    body = "".join(f"    (0x{a:x}, 0x{b:x}, {c}),\n" for a, b, c in rows)
    names = ", ".join(f"{i} {n}" for i, n in enumerate(CLASSES))
    out_path.write_text(
        "//! Grapheme cluster break classes as uucode 0.2.0 (Unicode 17.0, the data libghostty-vt 0.2.2\n"
        "//! builds with) derives them, generated by `tools/gen-grapheme-table.py` (DESIGN.md §10.7). Do not edit.\n\n"
        f"/// (first, last, class) for every code point not Other; classes: {names}.\n"
        f"pub const CLASSES: &[(u32, u32, u8)] = &[\n{body}];\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{out_path}: {len(rows)} ranges")


main()
