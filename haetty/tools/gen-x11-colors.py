#!/usr/bin/env python3
"""Writes haetty-vt's X11 colour names (crates/haetty-vt/src/x11_colors.rs).

usage: tools/gen-x11-colors.py RGB_TXT [OUT]

RGB_TXT is libghostty-vt's src/terminal/res/rgb.txt (in the libghostty-vt-sys
build output, out/ghostty-src/). Names are matched ignoring ASCII case, as
libghostty does (DESIGN.md §10.7).
"""
import pathlib
import sys

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "crates/haetty-vt/src/x11_colors.rs")
seen = {}
for line in src.read_text(encoding="utf-8").splitlines():
    line = line.rstrip("\r")
    if not line:
        continue
    r, g, b = int(line[0:3]), int(line[4:7]), int(line[8:11])
    name = line[12:].strip(" \t")
    # The first entry of a name (any case) wins, as in a map built in file order.
    seen.setdefault(name.lower(), (r, g, b))
rows = "".join(f'    ("{n}", [{r}, {g}, {b}]),\n' for n, (r, g, b) in sorted(seen.items()))
out.write_text(
    "//! X11 colour names (rgb.txt as libghostty-vt 0.2.2 has it), lower case and sorted, generated by\n"
    "//! `tools/gen-x11-colors.py` (DESIGN.md §10.7). Do not edit.\n\n"
    f"pub const X11: &[(&str, [u8; 3])] = &[\n{rows}];\n",
    encoding="utf-8",
    newline="\n",
)
print(f"{out}: {len(seen)} names")
